SRC_VERIFIED_NOUN = "research VERIFIED_NOUN_TRANSLATIONS (native-speaker answers)"
SRC_VERIFIED_ROOT = "research VERIFIED_ROOTS (native-speaker confirmed)"
SRC_VERIFIED_SENT = "research VERIFIED_SENTENCES (native-speaker sentences)"
SRC_WORDBANK_ADJ = "research Kitaita Word Bank adjective submissions, 2026-10-12/13"
SRC_CORPUS = "research corpus alignment (page1_vocabulary.json, Bible parallel text): statistical, not speaker-checked"
SRC_TAM_2026_10_07 = "native-speaker correction 2026-10-07 (research page3_verb_rules.json notes)"
SRC_PERSON_SM = "research PERSON_SUBJECT_MARKERS_BY_TAM"
SRC_NEG = "research negation tables (Kitaita Word Bank, 2026-10-15/21, n=1 per cell)"
SRC_CORPUS_AFFIX = ("corpus pattern: seen after speaker-verified roots in the Kitaita Bible corpus "
                    "(scripts/affix_evidence in status.md 2026-10-26); function guessed from Bantu typology, "
                    "NOT speaker-checked")
SRC_OM = "research KITAITA_PERSON_OBJECT_MARKER_HYPOTHESIS (corpus-inferred, NOT speaker-verified)"

NUMBER_BY_CLASS = {  # from nearest Swahili class in research kitaita_demonstrative_concord.json
    "u": "sg", "ghu": "sg", "ji": "sg", "i_nasal": "sg", "chi": "sg", "lu": "sg",
    "wi": "pl", "ghi": "pl", "va": "pl", "ri": "pl",
    "i": "ambiguous", "ku": "n/a", "gh": "unknown",
}
# u/wi are the animate classes in the research negation tables (they take the
# person-style negative template, not the ordinary class one).
ANIMATE_CLASSES = {"u", "wi"}


SOURCE_KEYS = {
    "verified_sm": SRC_VERIFIED_SM, "verified_noun": SRC_VERIFIED_NOUN, "verified_root": SRC_VERIFIED_ROOT,
    "class_table": "research class table (kitaita_demonstrative_concord.json sample_members)",
    "corpus": SRC_CORPUS, "kuwa_existential": "research VERIFIED_KUWA_ROOT_EXISTENTIAL",
    "kuwa_copula": "research VERIFIED_KUWA_ROOT_COPULA",
}
_KEY_OF = {v: k for k, v in SOURCE_KEYS.items()}


def compact_sources(rows: list[dict]) -> list[dict]:
    """Replace long source strings with SOURCE_KEYS keys (smaller files load
    faster in the browser). A Dice suffix ('; Dice 0.42') moves to `dice`."""
    for r in rows:
        if "sources" in r:
            r["sources"] = [_KEY_OF.get(x, x) for x in r["sources"]]
        if "source" in r:
            src = r["source"]
            if "; Dice " in src:
                src, dice = src.split("; Dice ")
                r["dice"] = float(dice)
            r["source"] = _KEY_OF.get(src, src)
    return rows


def dump_yaml(path: Path, header: str, obj) -> None:
    text = yaml.safe_dump(obj, allow_unicode=True, sort_keys=False, width=100)
    path.write_text(header.rstrip() + "\n" + text, encoding="utf-8")


def header(title: str, date: str, commit: str) -> str:
    return (f"# {title}\n# GENERATED by scripts/export_research_data.py from mpily/BantuGrammar@{commit} "
            f"on {date}.\n# Do not hand-edit: fix the research tables and re-export.\n")


def load_research(repo: Path):
    space = repo / "hf_space"
    sys.path.insert(0, str(space))
    cwd = os.getcwd()
    os.chdir(space)  # research loaders resolve their JSON files relative to cwd/__file__
    try:
        import kitaita_verified_corrections as v  # noqa: E402
        from kitaita_sentence_generator import build_lookup_tables, load_pages  # noqa: E402
        pages = load_pages()
        tables = build_lookup_tables(*pages)
        dem = json.loads((space / "kitaita_demonstrative_concord.json").read_text(encoding="utf-8"))
    finally:
        os.chdir(cwd)
    return v, tables, dem, pages[0]


def strip_fv(root: str) -> str:
    """Research Kitaita roots are sometimes stored with the final vowel -a
    (e.g. 'longoza', 'merea' for Sw. ongoz-/maliz-). The oracle adds FV
    itself, so a trailing -a is removed (roots of 3+ letters only)."""
    return root[:-1] if len(root) > 3 and root.endswith("a") else root


# --------------------------------------------------------------------------- concord
def build_concord(v, dem):
    classes = {}
    dem_by_id = {c["id"]: c for c in dem["classes"]}
    for cid in sorted(set(v.VERIFIED_SUBJECT_MARKERS.values()) | set(dem_by_id)):
        d = dem_by_id.get(cid, {})
        demonstratives = {}
        for deg in ("proximal", "referential", "distal"):
            cell = d.get(deg) or {}
            if cell.get("value"):
                demonstratives[deg] = {"form": cell["value"], "unverified": cell.get("status") != "verified"}
        classes[cid] = {
            "subject_marker": {"form": cid.replace("i_nasal", "i"), "unverified": False, "source": SRC_VERIFIED_SM},
            "nearest_swahili_class": d.get("nearest_swahili_class"),
            "number": NUMBER_BY_CLASS.get(cid, "unknown"),
            "animate": cid in ANIMATE_CLASSES,
            "present_fused_sm": ({"form": v.PRESENT_SM_VOWEL_CONFIRMED[cid], "unverified": False,
                                  "source": "research PRESENT_SM_VOWEL_CONFIRMED"}
                                 if cid in v.PRESENT_SM_VOWEL_CONFIRMED else None),
            "demonstratives": demonstratives,
            "sample_members": sorted(n for n, c in v.VERIFIED_SUBJECT_MARKERS.items() if c == cid)[:6],
            "adjective_prefixes": {"A": [], "B": []},  # filled by build_adjectives
        }
    return classes


# --------------------------------------------------------------------------- adjectives
def class_members(v, dem) -> dict[str, str]:
    """Kitaita noun -> class id: speaker answers first, then the research class
    table's member lists (kitaita_demonstrative_concord.json sample_members)."""
    out = {}
    for c in dem["classes"]:
        for n in c.get("sample_members", []):
            out.setdefault(n, c["id"])
    out.update(v.VERIFIED_SUBJECT_MARKERS)
    return out


def build_adjectives(v, classes, dem):
    sm_of = class_members(v, dem)
    stems = {}

    def add_stem(stem, swahili, forms, unverified, source):
        e = stems.setdefault(stem, {"stem": stem, "swahili": swahili, "series": None, "unverified": unverified,
                                    "source": source, "forms": {}})
        e["unverified"] = e["unverified"] and unverified
        for cid, form in forms.items():
            prev = e["forms"].get(cid)
            if prev is None or (prev["unverified"] and not unverified):
                e["forms"][cid] = {"form": form, "unverified": unverified, "source": source}

    # Word Bank submissions: same trust tier as other direct speaker answers
    add_stem("tini", "dogo", v.DOGO_FORM_BY_SM, False, SRC_WORDBANK_ADJ)
    add_stem("ghenyi", "geni", v.GENI_FORM_BY_SM, False, SRC_WORDBANK_ADJ)
    add_stem("vui", "fupi", v.FUPI_FORM_BY_SM, False, SRC_WORDBANK_ADJ)
    add_stem("lemere", "zito", v.ZITO_FORM_BY_SM, False, SRC_WORDBANK_ADJ)
    add_stem("lue", "chafu", v.CHAFU_FORM_BY_SM, False, SRC_WORDBANK_ADJ)
    # weaker tiers
    add_stem("baa", "kubwa", v.KUBWA_FORM_BY_SM, True, "research KUBWA_FORM_BY_SM (weaker tier than speaker answers)")
    add_stem("lacha", "refu", v.LACHA_FORM_BY_SM, True, "research LACHA_FORM_BY_SM (corpus Dice, partly n=1)")
    add_stem("ngi", "ingi", {}, True, "research INGI_FORM_BY_SM (forms listed as irregular)")
    for stem, sw, src in ((v.ZURI_ROOT, "zuri", "research ZURI_ROOT (corpus candidate)"),
                          (v.SAFI_STEM, "safi", "research SAFI_STEM"),
                          (v.MOJA_ROOT, "moja", "research MOJA_ROOT")):
        add_stem(stem, sw, {}, True, src)
    add_stem(v.BAYA_STEM, "baya", {}, False, "research BAYA_STEM (speaker-verified)")

    # forms inside speaker-verified sentences outrank the weaker tables
    stem_of_sw = {"kubwa": "baa", "baya": v.BAYA_STEM}
    noun_kit = dict(v.VERIFIED_NOUN_TRANSLATIONS)
    for (sw_noun, _root, _tam, adj), sentence in v.VERIFIED_SENTENCES.items():
        if adj not in stem_of_sw:
            continue
        words = sentence.rstrip(".").lower().split()
        kit_noun, adj_form = words[0], words[-1]
        cid = sm_of.get(kit_noun) or sm_of.get(noun_kit.get(sw_noun, ""))
        if cid:
            add_stem(stem_of_sw[adj], adj, {cid: adj_form}, False, SRC_VERIFIED_SENT)

    irregular = []
    for e in stems.values():
        forms = {cid: f["form"] for cid, f in e["forms"].items()}
        a_votes = sum([forms.get("chi", "").startswith("ki"), forms.get("u", "").startswith("m"),
                       forms.get("ghu", "").startswith("m")])
        b_votes = sum([forms.get("chi", "").startswith("chi"), forms.get("u", "").startswith("u"),
                       forms.get("ghu", "").startswith("ghu"), forms.get("ji", "").startswith("ji")])
        e["series"] = "A" if a_votes > b_votes else "B" if b_votes > a_votes else "unknown"
        for cid, f in e["forms"].items():
            form = f["form"]
            if form.endswith(e["stem"]) and len(form) > len(e["stem"]) and e["series"] in ("A", "B") \
                    and cid in classes:
                prefix = form[: -len(e["stem"])]
                plist = classes[cid]["adjective_prefixes"][e["series"]]
                hit = next((p for p in plist if p["form"] == prefix), None)
                if hit is None:
                    plist.append({"form": prefix, "unverified": f["unverified"], "evidence": [form]})
                else:
                    hit["unverified"] = hit["unverified"] and f["unverified"]
                    hit["evidence"].append(form)
                f["regular"] = True
            else:
                f["regular"] = False
                irregular.append(form)
    # INGI forms are suppletive-looking: list them as irregular attested forms
    ingi = stems["ngi"]
    for cid, form in v.INGI_FORM_BY_SM.items():
        ingi["forms"][cid] = {"form": form, "unverified": True, "regular": False,
                              "source": "research INGI_FORM_BY_SM"}
    return sorted(stems.values(), key=lambda e: e["stem"])


# --------------------------------------------------------------------------- nouns
def build_nouns(v, tables, classes, dem):
    noun_kitaita, noun_class_of = tables[0], tables[3]
    sw_of = defaultdict(set)
    for sw, kit in v.VERIFIED_NOUN_TRANSLATIONS.items():
        sw_of[kit.lower()].add(sw)
    entries = {}

    def put(form, cls, swahili, unverified, source):
        form = form.lower().strip()
        if not form or " " in form:
            return
        e = entries.get(form)
        if e is None:
            e = entries[form] = {"form": form, "class": None, "number": "unknown", "swahili": [],
                                 "unverified": True, "class_unverified": True, "sources": []}
        if cls and (e["class"] is None or (e["class_unverified"] and not unverified)):
            e["class"], e["class_unverified"] = cls, unverified
            e["number"] = classes.get(cls, {}).get("number", "unknown")
        for s in sorted(swahili):
            if s not in e["swahili"]:
                e["swahili"].append(s)
        e["unverified"] = e["unverified"] and unverified
        if source not in e["sources"]:
            e["sources"].append(source)

    for kit, cls in v.VERIFIED_SUBJECT_MARKERS.items():
        put(kit, cls, sw_of.get(kit, set()), False, SRC_VERIFIED_SM)
    for c in dem["classes"]:
        for kit in c.get("sample_members", []):
            put(kit, c["id"], sw_of.get(kit, set()), False, SOURCE_KEYS["class_table"])
    for sw, kit in v.VERIFIED_NOUN_TRANSLATIONS.items():
        put(kit, None, {sw}, False, SRC_VERIFIED_NOUN)
    for lemma, cand in noun_kitaita.items():
        if not str(cand.get("confidence", "")).startswith("high"):
            continue
        kit = cand.get("kitaita_word") or ""
        cls = (noun_class_of.get(kit) or {}).get("subject_marker")
        put(kit, cls, {lemma}, True, SRC_CORPUS)
    return sorted(entries.values(), key=lambda e: e["form"])


# --------------------------------------------------------------------------- roots
def build_roots(v, tables, min_corpus_score: float = 0.2):
    root_kitaita = tables[1]
    roots = {}
    for sw, kit in v.VERIFIED_ROOTS.items():
        r = strip_fv(kit)
        e = roots.setdefault(r, {"root": r, "swahili": [], "unverified": False, "source": SRC_VERIFIED_ROOT,
                                 "stored_form": kit})
        e["unverified"] = False
        e["source"] = SRC_VERIFIED_ROOT
        if sw not in e["swahili"]:
            e["swahili"].append(sw)
    roots.setdefault(v.VERIFIED_KUWA_ROOT_EXISTENTIAL, {"root": v.VERIFIED_KUWA_ROOT_EXISTENTIAL, "swahili": ["kuw"],
                     "unverified": False, "source": SOURCE_KEYS["kuwa_existential"], "note": "be (existential)"})
    roots.setdefault(v.VERIFIED_KUWA_ROOT_COPULA, {"root": v.VERIFIED_KUWA_ROOT_COPULA, "swahili": ["kuw"],
                     "unverified": False, "source": SOURCE_KEYS["kuwa_copula"], "note": "be (copula)"})
    for sw, cand in root_kitaita.items():
        kit = strip_fv(cand.get("kitaita_root") or "")
        score = cand.get("score") or 0
        if len(kit) < 3 or score < min_corpus_score or kit in roots:
            continue
        roots[kit] = {"root": kit, "swahili": [sw], "unverified": True,
                      "source": f"{SRC_CORPUS}; Dice {score:.2f}"}
    return sorted(roots.values(), key=lambda e: e["root"])


def build_swahili_roots(v, p1, min_count: int = 50):
    """Swahili roots for the parallel parser: confirmed-pair roots plus the
    research corpus's root guesses seen >= min_count times."""
    roots = {sw: {"root": sw, "source": "research VERIFIED_ROOTS keys"} for sw in v.VERIFIED_ROOTS}
    for vr in p1["verb_roots"]:
        r = vr.get("root_guess") or ""
        if len(r) >= 2 and vr.get("total_count", 0) >= min_count and r.isalpha():
            roots.setdefault(r, {"root": r, "source": f"research root guess, corpus count {vr['total_count']}"})
    return sorted(roots.values(), key=lambda e: e["root"])


