#!/usr/bin/env python3
"""Export Kitaita tables from the research repo into data/ (offline).

    python scripts/export_research_data.py /path/to/BantuGrammar [--date 2026-10-26]

Reads the research repo's speaker-verified tables
(hf_space/kitaita_verified_corrections.py: VERIFIED_*, Kitaita Word Bank
submissions, negation tables) and its corpus-alignment output
(hf_space/page1_vocabulary.json via build_lookup_tables) and writes:

  data/kitaita_concord.yaml       concord series per Kitaita class
  data/kitaita_nouns.yaml         noun forms (dictionary lookup only)
  data/kitaita_roots.yaml         verb roots
  data/kitaita_adjectives.yaml    adjective stems + attested forms
  data/kitaita_verb_slots.yaml    slot inventories + paradigms
  data/kitaita_phonology.yaml     morphophonological rules
  data/swahili_roots.yaml         Swahili verb roots (for the parallel parser)
  data/verified_vocab.json        speaker-verified word pairs for drills

Every row records its source. Rows that are not direct speaker answers
carry `unverified: true`. This script only reads research DATA tables; no
research pipeline code is copied into this repo. The research repo stays
the source of truth: fix a form there, then re-run this export.
"""
